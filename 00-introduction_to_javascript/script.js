// 2. What is ECMAScript?
// ECMAScript (ES) is a standard/specification that defines how scripting languages should work. JavaScript follows the ECMAScript standard.
// ECMAScript is maintained by ECMA International and is updated regularly with new features.

// Example:
let demo = "Hello";
console.log(demo);
// This is JavaScript code that follows the ECMAScript standard.


